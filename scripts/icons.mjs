import { icons } from 'lucide';
import { readdir, readFile, writeFile } from 'node:fs/promises';
async function sources(dir) {
    return (await Promise.all((await readdir(dir, { withFileTypes: true })).map(entry => entry.isDirectory() ? sources(`${dir}/${entry.name}`) : entry.name.endsWith('.js') ? readFile(`${dir}/${entry.name}`, 'utf8') : ''))).flat();
}
const source = [await readFile('index.html', 'utf8'), ...(await sources('js'))].join('\n');
const used = {};
for (const [name, tree] of Object.entries(icons)) {
    const kebab = name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([a-zA-Z])([0-9])/g, '$1-$2').toLowerCase();
    if (source.includes(kebab)) used[kebab] = tree;
}
const runtime = `/* Lucide icons, ISC license. See Lucide-LICENSE. Generated by scripts/icons.mjs. */
(() => {
const icons = ${JSON.stringify(used)};
const ns = 'http://www.w3.org/2000/svg';
function node([tag, attrs, children = []]) {
    const element = document.createElementNS(ns, tag);
    for (const [key, value] of Object.entries(attrs || {})) element.setAttribute(key, value);
    children.forEach(child => element.appendChild(node(child)));
    return element;
}
window.lucide = { createIcons(options = {}) {
    document.querySelectorAll('i[data-lucide]').forEach(element => {
        const name = element.dataset.lucide;
        if (!icons[name]) return;
        const svg = node(icons[name]);
        for (const attr of element.attributes) if (attr.name !== 'data-lucide') svg.setAttribute(attr.name, attr.value);
        svg.setAttribute('class', 'lucide lucide-' + name + ' ' + (element.className || ''));
        svg.setAttribute('aria-hidden', 'true');
        svg.setAttribute('focusable', 'false');
        for (const [key, value] of Object.entries(options.attrs || {})) svg.setAttribute(key, value);
        element.replaceWith(svg);
    });
} };
})();\n`;
await writeFile('vendor/lucide.min.js', runtime);
console.log(`${Object.keys(used).length} selected icons (${Math.round(runtime.length / 1024)} KB)`);
